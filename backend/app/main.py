"""FastAPI application factory."""
import logging
from contextlib import asynccontextmanager

from fastapi import FastAPI, Request
from fastapi.exceptions import RequestValidationError
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse
from starlette.exceptions import HTTPException as StarletteHTTPException

from .config import Settings, get_settings
from .database import Database
from .routes import chat
from .services import cache_service

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
logger = logging.getLogger("app")


def create_app(settings: Settings | None = None) -> FastAPI:
    settings = settings or get_settings()

    @asynccontextmanager
    async def lifespan(app: FastAPI):
        db = Database(settings.database_url)
        db.init()
        cache_service.configure_cache()
        app.state.db = db
        if len(settings.api_keys) < 2:
            logger.warning("Only %d API key(s) configured; failover needs at least 2.", len(settings.api_keys))
        logger.info(
            "Started: model=%s keys=%d simulation=%s",
            settings.llm_model, len(settings.api_keys), settings.enable_failure_simulation,
        )
        yield
        db.dispose()

    # Autogenerated docs/openapi routes are off so only the 3 contract endpoints exist.
    app = FastAPI(title="LLM Chatbot", docs_url=None, redoc_url=None, openapi_url=None, lifespan=lifespan)
    app.state.settings = settings

    app.add_middleware(
        CORSMiddleware,
        allow_origins=settings.origins,
        allow_methods=["GET", "POST", "OPTIONS"],
        allow_headers=["Content-Type", "X-Simulate-Failure"],
    )
    app.include_router(chat.router)

    @app.exception_handler(RequestValidationError)
    async def validation_handler(_: Request, exc: RequestValidationError):
        detail = [{"loc": list(e["loc"]), "msg": e["msg"], "type": e["type"]} for e in exc.errors()]
        return JSONResponse(status_code=422, content={"detail": detail})

    @app.exception_handler(StarletteHTTPException)
    async def http_handler(_: Request, exc: StarletteHTTPException):
        return JSONResponse(status_code=exc.status_code, content={"detail": exc.detail})

    @app.exception_handler(Exception)
    async def unhandled_handler(_: Request, exc: Exception):
        logger.error("Unhandled %s", type(exc).__name__)  # no message/trace: could contain secrets
        return JSONResponse(status_code=500, content={"detail": "internal server error"})

    return app


app = create_app()
